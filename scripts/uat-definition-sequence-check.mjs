import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {chromium} from '@playwright/test';

const base=process.env.FLOWDOC_PHASE1_URL??'http://127.0.0.1:5181';
const id=process.env.FLOWDOC_PAPER_DRAFT_ID,output=process.env.FLOWDOC_PAPER_EVIDENCE;
assert.ok(id&&output,'Set the UAT draft ID and evidence folder');
const directory=resolve(output);
await mkdir(directory,{recursive:true});
const browser=await chromium.launch({channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:960}});
page.setDefaultTimeout(5000);
const requests=[],errors=[];
page.on('request',request=>{
  const path=new URL(request.url()).pathname;
  if(path.startsWith('/api/'))requests.push({method:request.method(),path});
});
page.on('pageerror',error=>errors.push(error.message));
const api=base+'/api/editor-phase1/drafts/'+id;
const read=async()=>(await (await page.request.get(api)).json()).value;
const paper=page.locator('#paper'),viewport=page.locator('.definition-viewport');
const view=page.getByRole('button',{name:'ดูโครงต่อเนื่อง',exact:true});
const labels=paper.locator('[data-sequence-format]');
const sheet=paper.locator('.definition-sheet');
const photo=name=>page.screenshot({path:join(directory,name+'.png')});
try{
  const original=await read();
  await page.goto(base+'/phase1-editor.html?id='+id);
  await paper.getByRole('button',{name:'{{title}}',exact:true}).waitFor();
  assert.equal(await labels.count(),0);
  await view.click();
  assert.equal(await view.getAttribute('aria-pressed'),'true');
  await page.getByText('ตัวอย่างลำดับโครง', {exact:true}).waitFor();
  const keys=await labels.evaluateAll(nodes=>nodes.map(node=>node.dataset.sequenceFormat));
  assert.deepEqual(keys,Object.values(original.definition.areaFormats).map(format=>format.key));
  assert.equal(keys.length,14);
  assert.equal(await sheet.count(),2);
  assert.deepEqual(await sheet.first().locator('[data-sequence-format]').evaluateAll(nodes=>nodes.map(node=>node.dataset.sequenceFormat)),['cover','break']);
  const separator=sheet.first().getByRole('button',{name:/ขึ้นหน้าใหม่หลังจุดนี้/});
  await separator.evaluate(node=>node.scrollIntoView({block:'center'}));
  assert.match(await separator.textContent(),/break/);
  await separator.click();
  assert.match(await page.locator('#paper-selection').textContent(),/ขึ้นหน้าใหม่/);
  assert.ok(await paper.getByText('เริ่มหลังคำสั่งขึ้นหน้าใหม่', {exact:true}).isVisible());
  await photo('01-explicit-page-break');
  const summary=labels.filter({hasText:'summary-dynamic'});
  await summary.evaluate(node=>node.scrollIntoView({block:'center'}));
  assert.ok(await viewport.evaluate(node=>node.scrollTop>0));
  await photo('02-formats-in-the-document');
  await summary.click();
  const dialog=page.locator('#visual-definition-dialog');
  await dialog.getByRole('heading',{name:'แก้ Format · summary-dynamic'}).waitFor();
  assert.match(await page.locator('#paper-selection').textContent(),/summary-dynamic/);
  await photo('03-edit-from-format-label');
  const titleField=dialog.locator('[data-visual-field=label]');
  await titleField.locator('[data-visual-present]').check();
  await titleField.getByRole('textbox',{name:'ชื่อแสดงบนหน้าจอ'}).fill('ตารางสรุปที่แก้จากป้าย');
  await dialog.getByRole('button',{name:'ใช้กับโครงเอกสาร',exact:true}).click();
  await labels.filter({hasText:'10 · ตารางสรุปที่แก้จากป้าย'}).waitFor();
  await page.locator('#undo-structure').click();
  await summary.waitFor();
  assert.equal(await labels.count(),14);
  await page.getByRole('button',{name:'กลับไปดูทีละ Format'}).click();
  assert.equal(await view.getAttribute('aria-pressed'),'false');
  assert.equal(await labels.count(),0);
  await paper.getByRole('button',{name:'{{menu}}',exact:true}).waitFor();
  assert.ok(await page.locator('#save-structure').isDisabled());
  assert.ok(await page.locator('#structure-pending').isHidden());
  await page.goto(base+'/phase1-editor.html?id='+id+'&structureView=continuous');
  await labels.first().waitFor();
  assert.equal(await view.getAttribute('aria-pressed'),'true');
  assert.equal(await labels.count(),14);
  assert.deepEqual(await read(),original);
  assert.deepEqual(requests.filter(request=>request.method!=='GET'||request.path.includes('/preview')),[]);
  assert.deepEqual(errors,[]);
  const result={draftId:id,revision:original.revision,formats:keys,sheets:2,explicitBreak:'break',labelOpensFormatEditor:true,
    formatEditAndUndo:true,directLinkOpensSequence:true,
    returnToSelectedFormat:true,definitionUnchanged:true,writes:0,previewRequests:0};
  await writeFile(join(directory,'definition-sequence.json'),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result));
}finally{await browser.close();}
